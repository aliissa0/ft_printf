#include "libft.h"

void	*ft_calloc(size_t nmemb, size_t size)
{
	void	*p;

	if (size == 0 || nmemb == 0)
	{
		p = malloc(1);
		if (!p)
			return (NULL);
		ft_bzero(p, 1);
		return (p);
	}
	if (nmemb > 18446744073709551615UL / size)
		return (NULL);
	p = malloc(nmemb * size);
	if (!p)
		return (NULL);
	ft_bzero(p, (nmemb * size));
	return (p);
}
